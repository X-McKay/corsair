"""JavaScript build metadata (package.json, version files, lockfiles, CI) to SPEC-0042 declarations."""
import json
import re

from corsair.nodes.runtime.declarations import Collector, ci_versions
from corsair.nodes.runtime.versions import ANY, VersionSyntaxError, at_least, npm, parse_version, series, VersionSet, Interval

FRAMEWORKS = ('jest', 'mocha', 'ava', 'tap', 'tape', 'jasmine', 'vitest', '@hapi/lab', 'lab', 'qunit', 'karma')
CI_KEYS = ('node', 'node-version', 'node_version', 'nodejs', 'node-versions')


def _node(c: Collector, strength: str, source: str, path: str, needle: str, raw: str):
    raw = raw.strip().strip('\'"')
    raw = re.sub(r'(?<=\d)\.x$', '', raw)  # CI x-ranges: 18.x is the 18 series
    try:
        version = parse_version(raw)
    except VersionSyntaxError:
        c.unparsed('runtime', 'node', 'image', path, needle or raw, f'not a Node.js release: {raw!r}', strength=strength)
        return
    c.add('runtime', 'node', 'image', strength, source, path, needle or raw,
          series(version), listed=version)


def detect(c: Collector) -> None:
    text = c.text('package.json')
    package = {}
    if text is not None:
        try:
            package = json.loads(text)
            if not isinstance(package, dict): raise ValueError('not an object')
        except ValueError as error:
            c.unparsed('runtime', 'node', 'image', 'package.json', '', f'invalid package.json: {error}')
            package = {}
    engines = package.get('engines') if isinstance(package.get('engines'), dict) else {}
    for name in ('node', 'npm'):
        if isinstance(engines.get(name), str):
            kind = 'runtime' if name == 'node' else 'build_tool'
            try:
                c.add(kind, name, 'image', 'constraint', 'engines', 'package.json', f'"{name}"', npm(engines[name]))
            except VersionSyntaxError as error:
                c.unparsed(kind, name, 'image', 'package.json', f'"{name}"', str(error))
    manager = package.get('packageManager')
    if isinstance(manager, str) and (match := re.fullmatch(r'(npm|yarn|pnpm)@(\d+(?:\.\d+){0,7})(?:\+.*)?', manager)):
        version = parse_version(match[2])
        c.add('build_tool', match[1], 'image', 'pinned', 'packageManager', 'package.json', '"packageManager"', series(version), listed=version)
    if (lock := c.text('package-lock.json')) is not None:
        match = re.search(r'"lockfileVersion"\s*:\s*(\d+)', lock)
        if match:  # npm 5-6 write v1; npm 7+ write v2/v3 and read v1 with a rewrite
            versions = VersionSet((Interval((5,), True, (7,), False),)) if match[1] == '1' else at_least((7,))
            c.add('build_tool', 'npm', 'image', 'constraint', 'lockfile', 'package-lock.json', match[0], versions)
    elif 'yarn.lock' in c.files:
        classic = (c.text('yarn.lock') or '').startswith('# THIS IS AN AUTOGENERATED FILE') or '# yarn lockfile v1' in (c.text('yarn.lock') or '')[:400]
        c.add('build_tool', 'yarn', 'image', 'constraint', 'lockfile', 'yarn.lock', '', series((1,)) if classic else at_least((2,)))
    elif 'pnpm-lock.yaml' in c.files:
        c.add('build_tool', 'pnpm', 'image', 'constraint', 'lockfile', 'pnpm-lock.yaml', '', ANY)
    elif package:
        c.add('build_tool', 'npm', 'image', 'constraint', 'package', 'package.json', '{', ANY)
    for path in ('.nvmrc', '.node-version'):
        if (raw := c.text(path)) is not None:
            first = next((l.strip() for l in raw.splitlines() if l.strip()), '')
            _node(c, 'pinned', 'version-file', path, first, first.lstrip('v'))
    for path, value, source in ci_versions(c, CI_KEYS, ('node_js', 'node')):
        _node(c, 'tested', source, path, value, value)
    if (raw := c.text('appveyor.yml')) is not None:
        for match in re.finditer(r'nodejs_version\s*:\s*["\']?([\w.*]+)', raw):
            _node(c, 'tested', 'ci', 'appveyor.yml', match[0], match[1])
    _framework(c, package)


def _framework(c: Collector, package: dict) -> None:
    scripts = package.get('scripts') if isinstance(package.get('scripts'), dict) else {}
    dev = {**(package.get('dependencies') or {}), **(package.get('devDependencies') or {})} if isinstance(package.get('devDependencies', {}), dict) else {}
    # Follow `npm run x` indirections once from the test script, then look for a framework binary.
    command = str(scripts.get('test', ''))
    for name in re.findall(r'npm run ([\w:-]+)', command):
        command += ' ' + str(scripts.get(name, ''))
    named = [f for f in FRAMEWORKS if re.search(rf'(^|[\s/&;(]){re.escape(f)}(\s|$|;|&)', command)]
    source = 'test-script'
    if not named:
        named = [f for f in FRAMEWORKS if f in dev]
        source = 'devDependency'
        if len(named) != 1:
            if scripts.get('test') is not None:
                c.unparsed('test_framework', 'unknown', 'registry', 'package.json', '"test"',
                           'test script names no known framework' + (f'; devDependencies list {", ".join(named)}' if named else ''),
                           strength='tested')
            return
    for framework in named:
        spec = dev.get(framework)
        try:
            versions = npm(spec) if isinstance(spec, str) else ANY
        except VersionSyntaxError:
            c.unparsed('test_framework', framework, 'registry', 'package.json', f'"{framework}"', f'version {spec!r} not a semver range')
            continue
        c.add('test_framework', framework, 'registry', 'constraint', source, 'package.json',
              f'"{framework}"' if spec else '"test"', versions)
